using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

// Inspect product-declared symbols before restore, using the compiler shipped with the SDK.
// Actual builds and EF checks separately validate all external provider references.
var root = Path.GetFullPath(args.Single());
var platform = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator)
    .Select(path => MetadataReference.CreateFromFile(path)).ToArray();
var models = new Dictionary<string, CSharpCompilation>();
var projects = Directory.GetFiles(Path.Combine(root, "src"), "*.csproj", SearchOption.AllDirectories);
foreach (var project in projects.Order())
    InspectProject(project);

CSharpCompilation InspectProject(string project)
{
    if (models.TryGetValue(project, out var previous))
        return previous;
    var document = XDocument.Load(project);
    var directory = Path.GetDirectoryName(project)!;
    var references = new List<MetadataReference>(platform);
    foreach (var reference in document.Descendants("ProjectReference"))
    {
        var other = Path.GetFullPath(Path.Combine(directory, reference.Attribute("Include")!.Value.Replace('\\', '/')));
        references.Add(InspectProject(other).ToMetadataReference());
    }
    // The C# compiler sees project-to-project references transitively in these SDK projects.
    foreach (var dependency in references.OfType<CompilationReference>().ToArray())
        foreach (var transitive in dependency.Compilation.References.OfType<CompilationReference>())
            if (!references.OfType<CompilationReference>().Any(item => item.Compilation == transitive.Compilation))
                references.Add(transitive);

    string[] defaults = ["System", "System.IO", "System.Linq", "System.Collections.Generic", "System.Threading", "System.Threading.Tasks", "System.Net.Http"];
    var imports = document.Descendants("Using").Select(item =>
        (item.Attribute("Static")?.Value == "true" ? "static " : "") +
        (item.Attribute("Alias") is { } alias ? alias.Value + " = " : "") + item.Attribute("Include")?.Value);
    var globalUsings = CSharpSyntaxTree.ParseText(string.Join("\n", defaults.Concat(imports).Select(name => $"global using {name};")));
    var trees = new List<SyntaxTree>();
    foreach (var file in Directory.EnumerateFiles(directory, "*.cs", SearchOption.AllDirectories).Order())
    {
        var path = Path.GetRelativePath(root, file).Replace(Path.DirectorySeparatorChar, '/');
        if (path.Split('/').Any(part => part is "bin" or "obj" or "Migrations") ||
            new[] { ".g.cs", ".g.i.cs", ".generated.cs", ".Designer.cs" }.Any(suffix => path.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)))
            continue;
        var source = File.ReadAllText(file);
        if (source.Split('\n').Take(5).Any(line => line.TrimStart().StartsWith("//", StringComparison.Ordinal) && line.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase)))
            continue;
        trees.Add(CSharpSyntaxTree.ParseText(source, path: path));
    }
    var compilation = CSharpCompilation.Create(Path.GetFileNameWithoutExtension(project), trees.Append(globalUsings), references,
        new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
    models.Add(project, compilation);
    foreach (var tree in trees)
        InspectTree(tree, compilation.GetSemanticModel(tree, ignoreAccessibility: true));
    return compilation;
}

static void InspectTree(SyntaxTree tree, SemanticModel model)
{
    var unit = tree.GetCompilationUnitRoot();
    var path = tree.FilePath;
    var seen = new HashSet<(string Owner, string File, string Type)>();
    Console.WriteLine($"F\t{path}");
    foreach (var use in unit.DescendantNodes().OfType<UsingDirectiveSyntax>())
        EmitName(use, use.Name?.ToString());
    foreach (var name in unit.DescendantNodes().OfType<SimpleNameSyntax>())
    {
        // Qualified names also matter when a project reference or provider package is missing.
        if (name.Identifier.ValueText is "Alycia" or "Npgsql" or "Microsoft" or "System")
        {
            SyntaxNode outer = name;
            while (outer.Parent is QualifiedNameSyntax or AliasQualifiedNameSyntax or MemberAccessExpressionSyntax)
                outer = outer.Parent;
            if (outer != name)
                EmitName(name, outer.ToString());
        }

        var symbol = model.GetSymbolInfo(name).Symbol;
        var type = symbol switch
        {
            INamedTypeSymbol named => named,
            IMethodSymbol method when method.MethodKind == MethodKind.Constructor => method.ContainingType,
            IMethodSymbol method when method.IsExtensionMethod => (method.ReducedFrom ?? method).ContainingType,
            ISymbol member when name.Parent is MemberAccessExpressionSyntax access && access.Name == name
                && member.Kind is SymbolKind.Property or SymbolKind.Method or SymbolKind.Field => member.ContainingType,
            _ => null
        };
        if (type is not null && name.Ancestors().OfType<InterfaceDeclarationSyntax>().Any() &&
            (type.ContainingNamespace?.ToDisplayString() == "System.Net.Http" || type.ContainingNamespace?.ToDisplayString() == "System.Data.Common"))
            Console.WriteLine($"T\t{path}\t{Line(name)}\t{type.ToDisplayString()}");
        if (type is null || type.TypeKind == TypeKind.Error)
            continue;
        while (type.ContainingType is not null)
            type = type.ContainingType;
        var target = type.OriginalDefinition.Locations.FirstOrDefault(location => location.IsInSource)?.SourceTree?.FilePath;
        // A partial type can be referenced from any of its files, all of which have one owner.
        if (target is null || !target.StartsWith("src/", StringComparison.Ordinal))
            continue;
        var declaring = name.Ancestors().OfType<BaseTypeDeclarationSyntax>().LastOrDefault();
        var owner = declaring?.Identifier.ValueText ?? "";
        if (seen.Add((owner, target, type.Name)))
            Console.WriteLine($"R\t{path}\t{Line(name)}\t{owner}\t{target}\t{type.Name}");
    }
    // Endpoint exception translation may name DbUpdateException. Store queries belong to adapters.
    if (path.StartsWith("src/Alycia.Api/", StringComparison.Ordinal) &&
        path is not "src/Alycia.Api/Chat/ChatRegistration.cs" and not "src/Alycia.Api/Program.cs")
        foreach (var token in unit.DescendantTokens().Where(t => t.IsKind(SyntaxKind.IdentifierToken)))
            if (token.ValueText is "ChatDbContext" or "WorkspacesDbContext" or "DbContext" or "DbSet" or "DatabaseFacade" or "AddDbContext"
                or "ExecuteUpdate" or "ExecuteUpdateAsync" or "ExecuteDelete" or "ExecuteDeleteAsync" ||
                token.ValueText.StartsWith("FromSql", StringComparison.Ordinal) ||
                token.ValueText.StartsWith("ExecuteSql", StringComparison.Ordinal) || token.ValueText.StartsWith("SqlQuery", StringComparison.Ordinal))
                Console.WriteLine($"P\t{path}\t{token.GetLocation().GetLineSpan().StartLinePosition.Line + 1}\t{token.ValueText}");

    void EmitName(SyntaxNode node, string? value)
    {
        if (value is not null)
            Console.WriteLine($"N\t{path}\t{Line(node)}\t{value.Replace("global::", "").ReplaceLineEndings(" ")}");
    }
}

static int Line(SyntaxNode node) => node.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
